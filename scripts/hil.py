#!/usr/bin/env python3
"""
AutoQrypt: ESP32 Hardware-in-the-Loop signer and test runner.

  python scripts/hil.py keys
      Writes firmware/main/trusted_keys.h (public keys + key ids pinned into the ECU).

  python scripts/hil.py run COM7 [--dashboard http://127.0.0.1:7001/ingest]
      Builds signed packages from firmware/build/autoqrypt-ecu-surrogate.bin, sends them to
      the ESP32 over UART, and records the admission decision for each test case in
      measurements/hil_results.json. Expects a freshly flashed board (security version 1).

Wire format (must match firmware/main/main.c):
  frame    = "AQPK" | manifest(108) | falcon512_sig(666) | ed25519_sig(64) | mldsa44_sig(2420)
             then, only after the ECU answers "AQ:SEND", the image in 4096-byte chunks,
             each acknowledged with "AQ:ACK <bytes>".
  "AQBM" | header  repeats the three verifiers on the device (benchmark, installs nothing).
  "AQLD"           asks the idle ECU to repeat the current package's decision line.
  manifest = "AQM1" | u16 format=1 | u8 hash=1 (SHA3-256) | u8 flags=0
             | target_id[16] | version[16] | u32 security_version | u32 image_size
             | alg ids (1=Ed25519, 2=ML-DSA-44, 3=Falcon-512, 0) | key ids 3 x 8 | sha3_256(image)
  Image role signs    "AQ-IMAGE-V1" | manifest           (Ed25519 AND ML-DSA-44)
  Director signs      "AQ-DIRECTOR-V1" | vehicle_id[16] | manifest   (Falcon-512)
"""

import argparse
import datetime
import hashlib
import json
import os
import struct
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from key_management.hsm import SimulatedHSM  # noqa: E402

KEYS_HEADER = os.path.join(ROOT, "firmware", "main", "trusted_keys.h")
IMAGE_BIN = os.path.join(ROOT, "firmware", "build", "autoqrypt-ecu-surrogate.bin")
RESULTS = os.path.join(ROOT, "measurements", "hil_results.json")

TARGET_ID = "ESP32-ECU-GW"
VEHICLE_ID = "VEH-1"
CHUNK = 4096

# Same seeds as main.py, so the ECU pins the same keys as the Python demo.
ED25519_SEED = b"deterministic_image_hsm_seed_offline_oem_key"
MLDSA_SEED = b"deterministic_image_pqc_hsm_seed_offline_oem_key"
DIRECTOR_SEED = b"deterministic_director_hsm_seed_online_fleet_key"


def load_keys():
    return {
        "ed25519": SimulatedHSM(seed=ED25519_SEED, algorithm="ED25519"),
        "mldsa44": SimulatedHSM(seed=MLDSA_SEED, algorithm="ML-DSA-44", use_qrng=True),
        "falcon512": SimulatedHSM(seed=DIRECTOR_SEED, algorithm="FALCON-512"),
    }


def key_id(pk: bytes) -> bytes:
    return hashlib.sha3_256(pk).digest()[:8]


def pad16(s: str) -> bytes:
    b = s.encode()
    assert 0 < len(b) <= 16
    return b.ljust(16, b"\0")


# ------------------------------------------------------------------ keys header

def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def cmd_keys(_args):
    keys = load_keys()
    out = [
        "// Generated by scripts/hil.py keys -- do not edit. Public keys only.\n",
        "#pragma once\n#include <stdint.h>\n\n",
        f'#define DEVICE_TARGET_ID  "{TARGET_ID}"\n',
        f'#define DEVICE_VEHICLE_ID "{VEHICLE_ID}"\n\n',
    ]
    for name, hsm in keys.items():
        pk = hsm.get_public_key_bytes()
        out.append(c_array(f"TRUSTED_{name.upper()}_PK", pk))
        out.append(c_array(f"TRUSTED_{name.upper()}_KEY_ID", key_id(pk)))
        out.append("\n")
    with open(KEYS_HEADER, "w", newline="\n") as f:
        f.writelines(out)
    print(f"[+] Wrote {os.path.relpath(KEYS_HEADER, ROOT)}")
    for name, hsm in keys.items():
        pk = hsm.get_public_key_bytes()
        print(f"    {name:10s} {len(pk):5d} B  key id {key_id(pk).hex()}")


# ------------------------------------------------------------------ packages

def make_manifest(image, keys, target=TARGET_ID, version="v2.0.0", security_version=2,
                  mldsa_pk=None, magic=b"AQM1"):
    ids = key_id(keys["ed25519"].get_public_key_bytes()) \
        + key_id(mldsa_pk or keys["mldsa44"].get_public_key_bytes()) \
        + key_id(keys["falcon512"].get_public_key_bytes())
    m = (magic + struct.pack("<HBB", 1, 1, 0) + pad16(target) + pad16(version)
         + struct.pack("<II", security_version, len(image)) + bytes([1, 2, 3, 0])
         + ids + hashlib.sha3_256(image).digest())
    assert len(m) == 108
    return m


def sign_header(manifest, keys, vehicle=VEHICLE_ID, mldsa_hsm=None):
    image_msg = b"AQ-IMAGE-V1" + manifest
    director_msg = b"AQ-DIRECTOR-V1" + pad16(vehicle) + manifest
    falcon = keys["falcon512"].sign(director_msg)
    ed = keys["ed25519"].sign(image_msg)
    mldsa = (mldsa_hsm or keys["mldsa44"]).sign(image_msg)
    assert (len(falcon), len(ed), len(mldsa)) == (666, 64, 2420)
    return bytearray(manifest + falcon + ed + mldsa)


def flip(buf: bytearray, offset: int) -> bytearray:
    out = bytearray(buf)
    out[offset] ^= 0x01
    return out


FALCON_OFF, ED_OFF, MLDSA_OFF = 108, 108 + 666, 108 + 666 + 64


def build_cases(image, keys):
    """(id, description, header, image, mode, expected decision, expected reason)."""
    valid = sign_header(make_manifest(image, keys), keys)
    rogue = SimulatedHSM(seed=b"attacker_rogue_mldsa_key", algorithm="ML-DSA-44")
    tampered_manifest = bytearray(valid)
    tampered_manifest[40:44] = struct.pack("<I", 99)  # bump security_version without re-signing
    bad_image = bytearray(image)
    bad_image[len(image) // 2] ^= 0x01

    pre = [
        ("T09a", "Malformed manifest (bad magic)",
         sign_header(make_manifest(image, keys, magic=b"XXXX"), keys), image, "full", "REJECT", "MALFORMED_MANIFEST_MAGIC"),
        ("T09b", "Truncated header (stream stops after 500 bytes)",
         valid[:500], image, "truncate_header", "REJECT", "TRUNCATED_HEADER"),
        ("T06", "Wrong target (validly signed for ESP32-ECU-BRK)",
         sign_header(make_manifest(image, keys, target="ESP32-ECU-BRK"), keys), image, "full", "REJECT", "WRONG_TARGET"),
        ("T07", "Downgrade (validly signed v1.0.0, security version 1)",
         sign_header(make_manifest(image, keys, version="v1.0.0", security_version=1), keys), image, "full",
         "REJECT", "ROLLBACK_ATTACK_DETECTED"),
        ("T08a", "Untrusted ML-DSA key (rogue key id)",
         sign_header(make_manifest(image, keys, mldsa_pk=rogue.get_public_key_bytes()), keys, mldsa_hsm=rogue), image,
         "full", "REJECT", "UNTRUSTED_MLDSA44_KEY_ID"),
        ("T08b", "Rogue ML-DSA signature claiming the trusted key id",
         sign_header(make_manifest(image, keys), keys, mldsa_hsm=rogue), image, "full",
         "REJECT", "IMAGE_MLDSA44_SIGNATURE_INVALID"),
        ("T13a", "Corrupted Falcon-512 director signature",
         flip(valid, FALCON_OFF + 300), image, "full", "REJECT", "DIRECTOR_FALCON512_SIGNATURE_INVALID"),
        ("T13b", "Director-signed for a different vehicle (VEH-2)",
         sign_header(make_manifest(image, keys), keys, vehicle="VEH-2"), image, "full",
         "REJECT", "DIRECTOR_FALCON512_SIGNATURE_INVALID"),
        ("T03", "Corrupted Ed25519 signature only",
         flip(valid, ED_OFF + 10), image, "full", "REJECT", "IMAGE_ED25519_SIGNATURE_INVALID"),
        ("T04", "Corrupted ML-DSA-44 signature only",
         flip(valid, MLDSA_OFF + 1000), image, "full", "REJECT", "IMAGE_MLDSA44_SIGNATURE_INVALID"),
        ("T05", "Both image signatures corrupted",
         flip(flip(valid, ED_OFF + 10), MLDSA_OFF + 1000), image, "full", "REJECT", "IMAGE_ED25519_SIGNATURE_INVALID"),
        ("T06b", "Manifest security version changed after signing",
         tampered_manifest, image, "full", "REJECT", "DIRECTOR_FALCON512_SIGNATURE_INVALID"),
        ("T02", "One firmware byte flipped after signing",
         valid, bytes(bad_image), "full", "REJECT", "IMAGE_DIGEST_MISMATCH"),
        ("T10", "Transfer interrupted after 64 KB",
         valid, image, "interrupt", "REJECT", "TRANSFER_INTERRUPTED"),
    ]
    post = [
        ("T01", "Valid v2.0.0 package (all signatures valid)", valid, image, "full", "ACCEPT", "ALL_CHECKS_PASSED"),
        ("T07b", "Replay of the accepted v2.0.0 package", valid, image, "full", "REJECT", "ROLLBACK_ATTACK_DETECTED"),
    ]
    return valid, pre, post


# ------------------------------------------------------------------ serial runner

def is_decision(x):
    return isinstance(x, dict) and x.get("event_type") == "ota_decision"


def is_garbled(x):
    return isinstance(x, str) and "�" in x


class ECU:
    def __init__(self, port, dashboard=None):
        import serial
        self.ser = serial.Serial()
        self.ser.port, self.ser.baudrate, self.ser.timeout = port, 115200, 0.2
        self.ser.dtr = self.ser.rts = False  # don't hold the board in reset/bootloader
        self.ser.open()
        self.dashboard = dashboard
        self.log = []
        self._partial = b""
        self.resends = 0

    def reset(self):
        self.ser.rts = True
        time.sleep(0.1)
        self.ser.rts = False

    def line(self, deadline):
        while time.time() < deadline:
            # readline() returns early on timeout; keep partial lines until the newline arrives
            self._partial += self.ser.readline()
            if not self._partial.endswith(b"\n"):
                continue
            raw, self._partial = self._partial, b""
            text = raw.decode("utf-8", errors="replace").strip()
            if not text:
                continue
            self.log.append(text)
            if text.startswith("{") and text.endswith("}"):
                try:
                    event = json.loads(text)
                except json.JSONDecodeError:
                    return text
                self.forward(event)
                return event
            return text
        return None

    def wait_for(self, pred, timeout):
        deadline = time.time() + timeout
        while True:
            item = self.line(deadline)
            if item is None:
                return None
            if pred(item):
                return item

    def forward(self, event):
        if not self.dashboard:
            return
        try:
            import requests
            event.setdefault("timestamp", datetime.datetime.now().isoformat())
            requests.post(self.dashboard, json=event, timeout=2)
        except Exception as e:
            print(f"    [dashboard forward failed: {e}]")

    def resend_decision(self):
        """Asks the (idle) ECU to repeat its last decision line after a garbled or missing one.

        The CP2102 link on the test bench intermittently delivers the first 64-byte USB packet
        after ~5 s of idle as 0xFF. The ECU only accepts "AQLD" between packages, and it never
        repeats an earlier package's decision.
        """
        self.resends += 1
        self.ser.write(b"AQLD")
        return self.wait_for(is_decision, 10)

    def send_package(self, header, image, mode):
        """Returns the ECU's ota_decision event, or None on timeout."""
        self.resends = 0
        self.ser.write(b"AQPK" + bytes(header))
        if mode == "truncate_header":
            item = self.wait_for(lambda x: is_decision(x) or is_garbled(x), 15)
            return item if is_decision(item) else self.resend_decision()
        # The ECU erases the target slot before asking for the image, so allow time.
        item = self.wait_for(lambda x: x == "AQ:SEND" or is_decision(x) or is_garbled(x), 60)
        if item != "AQ:SEND":
            return item if is_decision(item) else self.resend_decision()
        limit = 64 * 1024 if mode == "interrupt" else len(image)
        for off in range(0, limit, CHUNK):
            self.ser.write(image[off:off + CHUNK])
            item = self.wait_for(lambda x: (isinstance(x, str) and x.startswith("AQ:ACK")) or is_decision(x)
                                 or is_garbled(x), 15)
            if is_decision(item):
                return item
            if item is None or is_garbled(item):
                return self.resend_decision()
            done = min(off + CHUNK, len(image))
            print(f"\r    streaming {done * 100 // len(image):3d}%", end="", flush=True)
        print()
        item = self.wait_for(lambda x: is_decision(x) or is_garbled(x), 30)
        return item if is_decision(item) else self.resend_decision()

    def send_bench(self, header):
        self.ser.write(b"AQBM" + bytes(header))
        return self.wait_for(lambda x: isinstance(x, dict) and x.get("event_type") == "bench_report", 120)


def cmd_run(args):
    if not os.path.exists(IMAGE_BIN):
        sys.exit(f"[!] {IMAGE_BIN} not found. Build the firmware first.")
    with open(IMAGE_BIN, "rb") as f:
        image = f.read()
    keys = load_keys()
    valid, pre, post = build_cases(image, keys)

    ecu = ECU(args.port, args.dashboard)
    print(f"[*] Resetting ECU on {args.port} ...")
    ecu.reset()
    boot = ecu.wait_for(lambda x: isinstance(x, dict) and x.get("event_type") == "boot_report", 15)
    if not boot or not ecu.wait_for(lambda x: x == "AQ:READY", 10):
        sys.exit("[!] ECU did not boot. Is the AutoQrypt firmware flashed?")
    print(f"[*] ECU booted: slot {boot['running_slot']}, security version {boot['installed_security_version']}")
    if boot["installed_security_version"] != 1:
        sys.exit("[!] Expected a fresh board at security version 1. Run: idf.py -p PORT erase-flash flash")

    results = []

    def run_case(case):
        cid, desc, header, img, mode, exp_dec, exp_reason = case
        print(f"[{cid}] {desc}")
        start = len(ecu.log)
        t0 = time.time()
        ev = ecu.send_package(header, img, mode)
        actual = (ev or {}).get("decision", "TIMEOUT"), (ev or {}).get("reason", "TIMEOUT")
        passed = actual == (exp_dec, exp_reason)
        print(f"    expected {exp_dec}/{exp_reason}  actual {actual[0]}/{actual[1]}  -> {'PASS' if passed else 'FAIL'}")
        results.append({
            "id": cid, "description": desc, "expected": {"decision": exp_dec, "reason": exp_reason},
            "actual": {"decision": actual[0], "reason": actual[1]}, "pass": passed,
            "wall_time_s": round(time.time() - t0, 2), "device_event": ev, "decision_resends": ecu.resends,
            "header_sha3_256": hashlib.sha3_256(bytes(header)).hexdigest(),
            "image_sha3_256": hashlib.sha3_256(img).hexdigest(),
        })
        return ev

    for case in pre:
        run_case(case)
        if not ecu.wait_for(lambda x: x == "AQ:READY", 15):
            print("    [!] ECU did not return to READY")

    print("[BENCH] Verifier timing, valid header, repeated on device")
    bench = ecu.send_bench(valid)
    ecu.wait_for(lambda x: x == "AQ:READY", 15)
    if bench:
        for k in ("falcon512_director", "ed25519_image", "mldsa44_image"):
            b = bench[k]
            print(f"    {k:20s} median {b['median_us']:7d} us  (min {b['min_us']}, max {b['max_us']})  stack {b['stack_peak_bytes']} B")

    run_case(post[0])
    reboot = ecu.wait_for(lambda x: isinstance(x, dict) and x.get("event_type") == "boot_report", 30)
    ecu.wait_for(lambda x: x == "AQ:READY", 10)
    if reboot:
        print(f"    rebooted into {reboot['running_slot']}, security version {reboot['installed_security_version']},"
              f" confirmed on first boot: {reboot['confirmed_on_this_boot']}")
    results[-1]["post_reboot"] = reboot
    results[-1]["pass"] = bool(results[-1]["pass"] and reboot and reboot["running_slot"] != boot["running_slot"]
                               and reboot["installed_security_version"] == 2 and reboot["confirmed_on_this_boot"])
    run_case(post[1])

    rejected_inactive = all(r["device_event"] and r["device_event"].get("running_slot") == boot["running_slot"]
                            for r in results if r["expected"]["decision"] == "REJECT" and r["id"] != "T07b")
    report = {
        "generated": datetime.datetime.now().isoformat(timespec="seconds"),
        "measurement_type": "physical hardware (ESP32 over USB-UART)",
        "port": args.port,
        "software": {"pqclean_commit": "0586a824fc0d49df0b6b6e9179d8d15d06d0974f", "monocypher": "4.0.2"},
        "sizes_bytes": {"manifest": 108, "falcon512_sig": 666, "ed25519_sig": 64, "mldsa44_sig": 2420,
                        "header_total": 4 + len(valid), "image": len(image)},
        "initial_boot": boot,
        "rejected_packages_left_running_slot_unchanged": rejected_inactive,
        "bench": bench,
        "tests": results,
        "serial_log": ecu.log,
    }
    os.makedirs(os.path.dirname(RESULTS), exist_ok=True)
    with open(RESULTS, "w") as f:
        json.dump(report, f, indent=2)
    n_pass = sum(r["pass"] for r in results)
    print(f"\n[*] {n_pass}/{len(results)} tests passed. Rejected packages never changed the running slot: {rejected_inactive}")
    print(f"[*] Results written to {os.path.relpath(RESULTS, ROOT)}")
    sys.exit(0 if n_pass == len(results) and rejected_inactive else 1)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("keys", help="write firmware/main/trusted_keys.h")
    r = sub.add_parser("run", help="run the HIL test matrix on the ESP32")
    r.add_argument("port")
    r.add_argument("--dashboard", help="forward device JSON to this /ingest URL")
    args = p.parse_args()
    {"keys": cmd_keys, "run": cmd_run}[args.cmd](args)


if __name__ == "__main__":
    main()
